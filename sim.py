# ----------------------------------------------------------------- model --
def cum_effect(rho, H):
    """C_j(H): cumulative effect realized within H months of a unit flow
    response with geometric monthly retention rho."""
    return (1.0 - rho ** H) / (1.0 - rho)


def weight(H, rho_L, rho_S):
    """w(H) = C_L(H) / (C_L(H) + C_S(H))."""
    cL, cS = cum_effect(rho_L, H), cum_effect(rho_S, H)
    return cL / (cL + cS)


def resp_power(x, scale, a):
    return scale * np.power(np.clip(x, 0, 1), a)


def resp_log(x, scale, k):
    return scale * np.log1p(k * np.clip(x, 0, 1)) / np.log1p(k)


def resp_hill(x, scale, n, c):
    x = np.clip(x, 0, 1)
    return scale * (x ** n / (x ** n + c ** n)) * ((1 + c ** n) / 1.0)


def objective(b, H, p, form="power", phi_weighted=False):
    """R_H(b) = w(H) L(b) + (1 - w(H)) S(1 - b) + phi(B(b), 1 - b).

    B(b) = b ** a_L is the normalized brand-building stock (0 at b = 0, 1 at b = 1).
    phi(B, 1 - b) = gamma * B * S(1 - b) captures complementarity: brand-building
    stock raises the yield of activation.
    """
    w = weight(H, p["rho_L"], p["rho_S"])
    if form == "power":
        L = resp_power(b, p["ell"], p["a_L"])
        S = resp_power(1 - b, p["s"], p["a_S"])
    elif form == "log":
        L = resp_log(b, p["ell"], p["k_L"])
        S = resp_log(1 - b, p["s"], p["k_S"])
    elif form == "hill":
        L = resp_hill(b, p["ell"], p["n_L"], p["c_L"])
        S = resp_power(1 - b, p["s"], p["a_S"])
    else:
        raise ValueError(form)
    B = np.power(np.clip(b, 0, 1), p["a_L"])
    phi = p["gamma"] * B * S
    if phi_weighted:
        phi = (1 - w) * phi
    return w * L + (1 - w) * S + phi


def solve(H, p, form="power", phi_weighted=False, refine=True):
    """Global grid search on [0, 1] then bounded refinement around the grid
    maximizer. Constraint: b in [0, 1]."""
    R = objective(B_GRID, H, p, form, phi_weighted)
    i = int(np.argmax(R))
    b0 = B_GRID[i]
    if not refine:
        return b0
    lo, hi = max(0.0, b0 - 0.001), min(1.0, b0 + 0.001)
    if hi - lo < 1e-9:
        return b0
    res = minimize_scalar(lambda x: -objective(np.array(x), H, p, form, phi_weighted),
                          bounds=(lo, hi), method="bounded", options={"xatol": 1e-7})
    cand = [(b0, R[i]), (res.x, -res.fun)]
    return float(max(cand, key=lambda t: t[1])[0])


# --------------------------------------------------------------- helpers --
def draw_params(rng, n, overrides=None):
    d = {k: rng.uniform(*v, size=n) for k, v in RANGES.items()}
    d["ell"] = BASE["ell"] * d.pop("ell_mult")
    d["s"] = np.full(n, BASE["s"])
    if overrides:
        for k, f in overrides.items():
            d[k] = f(rng, n, d)
    return [{k: float(v[j]) for k, v in d.items()} for j in range(n)]


def bstar_path(p, form="power", phi_weighted=False):
    """b*(H) over H_GRID, vectorized grid solve (step 0.0005)."""
    w = weight(H_GRID[:, None], p["rho_L"], p["rho_S"])
    b = B_GRID[None, :]
    if form == "power":
        L = resp_power(b, p["ell"], p["a_L"]); S = resp_power(1 - b, p["s"], p["a_S"])
    elif form == "log":
        L = resp_log(b, p["ell"], p["k_L"]); S = resp_log(1 - b, p["s"], p["k_S"])
    elif form == "hill":
        L = resp_hill(b, p["ell"], p["n_L"], p["c_L"]); S = resp_power(1 - b, p["s"], p["a_S"])
    phi = p["gamma"] * np.power(b, p["a_L"]) * S
    if phi_weighted:
        phi = (1 - w) * phi
    R = w * L + (1 - w) * S + phi
    return B_GRID[np.argmax(R, axis=1)]


def summarize(paths, tol=1e-3):
    paths = np.asarray(paths)
    hi = {h: int(np.where(H_GRID == h)[0][0]) for h in (6, 36)}
    nondecr = np.all(np.diff(paths, axis=1) >= -tol, axis=1)
    corner = np.any((paths <= 0.0005) | (paths >= 0.9995), axis=1)
    return dict(
        median_b6=round(float(np.median(paths[:, hi[6]])), 3),
        median_b36=round(float(np.median(paths[:, hi[36]])), 3),
        pct_nondecreasing=round(100 * float(nondecr.mean()), 1),
        pct_corner=round(100 * float(corner.mean()), 1),
        pct_strict_decrease_6_36=round(100 * float((paths[:, hi[36]] < paths[:, hi[6]] - tol).mean()), 1),
        pct_strict_increase_6_36=round(100 * float((paths[:, hi[36]] > paths[:, hi[6]] + tol).mean()), 1),
    )


def rel_lum(hexc):
    c = [int(hexc[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def contrast(fg, bg="#ffffff"):
    a, b = sorted([rel_lum(fg), rel_lum(bg)], reverse=True)
    return (a + 0.05) / (b + 0.05)


